    private void BuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BuscarActionPerformed
        // TODO add your handling code here:
        
         Equipamento equipamento = new Equipamento();
        EquipamentoDAO equipamentoDao = new EquipamentoDAO();
        
        String patrimonio;
        
        patrimonio = Patrimonio.getText();
        equipamento.setPatrimonio(patrimonio);
        
        try {
            equipamentoDao.pesquisar(equipamento );
            if(equipamento .getNome() != null) {
                dadosEquipamento.setText(   "Nome: " + equipamento.getNome() + "\n"
    + "Descrição: " + equipamento.getDescricao() + "\n"
    + "Marca: " + equipamento.getMarca() + "\n"
    + "Patrimônio: " + equipamento.getPatrimonio() + "\n"
    + "Sala: " + equipamento.getSala() + "\n"
    + "Quantidade: " + equipamento.getQuantidade() + "\n"
    + "Estado de Conservação: " + equipamento.getEstadoConservacao() + "\n");
                } else { 
                 dadosEquipamento.setText("Equipamento não encontrado");
            }
            
            } catch (SQLException ex) {
            System.out.println("Não encontrado \n" +ex);
        }
    }//GEN-LAST:event_BuscarActionPerformed

