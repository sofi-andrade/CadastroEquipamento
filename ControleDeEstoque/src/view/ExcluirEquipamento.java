    private void ExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ExcluirActionPerformed
        // TODO add your handling code here:
          
        Equipamento equipamento = new Equipamento();
        EquipamentoDAO equipamentoDao = new EquipamentoDAO();

        int  n1 = Integer.parseInt(JOptionPane.showInputDialog("Deseja excluir? 1. SIM 2 NÃO"));

        if(n1 ==1){
            String patrimonio;

          //patrimonio = dadosBox.getText();
          patrimonio = Patrimonio.getText();
            equipamento.setPatrimonio(patrimonio);

            try {
                equipamentoDao.excluir(equipamento);
                JOptionPane.showMessageDialog(null, "Equipamento excluído com sucesso");
                Patrimonio.setText("");
                dadosEquipamento.setText("");

            } catch (SQLException ex) {
               JOptionPane.showMessageDialog(null, "Erro ao excluir: " + ex.getMessage());
                ex.printStackTrace();
            }

        } else {
            JOptionPane.showMessageDialog(null, "Exclusão cancelada");
        }

    
      
    }//GEN-LAST:event_ExcluirActionPerformed

